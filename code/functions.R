  dplyr::group_by(replicate, condition)%>%
  dplyr::mutate(neg_ref = rowMeans(across(all_of(neg_col)), na.rm = TRUE), 
                pos_ref =rowMeans(across(all_of(pos_col)), na.rm = TRUE))

