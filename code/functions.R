# Function to read the fasta files with the sequencing reads
import_reads <- 
  function(sample_name, suffix){
    sample_name <- paste0(suffix, sample_name)
    test_data <- readDNAStringSet(sample_name)
    id_reads <- names(test_data)
    id_reads <-
      as_tibble(matrix(unlist(strsplit(id_reads, ';')), ncol = 2, byrow = T))
    id_reads$sequence <- as.character(test_data)
    colnames(id_reads) <- c('id', 'number', 'sequence')
    
    id_reads$number <-
      gsub(pattern = 'size=', replacement = '', id_reads$number)
    
    return(id_reads)
  }


# Function to get the number of generation using the OD values recorderd at each timepoint
get_generation <- 
  function(end_od, start_od = 0.1){
    x <- start_od
    g = 0
    while (x < end_od) {
      g = g+1
      if(x*2 < end_od){
        x <- x*2 
        next
      } else if(x*2 >= end_od){
        dif <- end_od - x
        g <- g + dif/x
        return(g)
        break
      }
    }
  }


