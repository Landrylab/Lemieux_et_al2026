#+++++++++++++++++++++++++
# Function to calculate the mean and the standard deviation
# for each group
#+++++++++++++++++++++++++
# data : a data frame
# varname : the name of a column containing the variable
#to be summariezed
# groupnames : vector of column names to be used as
# grouping variables
data_summary <- function(data, varname, groupnames){
  require(plyr)
  summary_func <- function(x, col){
    c(mean = mean(x[[col]], na.rm=TRUE),
      sd = sd(x[[col]], na.rm=TRUE))
  }
  data_sum<-ddply(data, groupnames, .fun=summary_func,
                  varname)
  data_sum <- rename(data_sum, c("mean" = varname))
  return(data_sum)
}


# Function to compute the PWM score for all sequences generated by degenerating one position in the PWM
get_PWM_score <-
  function(sub_PWM, deg_pos) {
    seq <- ''
    score <- 0
    
    for (i in 1:nrow(sub_PWM)) {
      
      if (i %in% c(deg_pos$pos1)) {
        print('deg1')
        
        aa <- colnames(sub_PWM[i, ])
        part_score <- unlist(sub_PWM[i, ])
        #print(aa)
        seq <- str_c(seq, aa)
        #print(part_seq)
        score <- score + part_score
        
      }
      
      if (i %in% c(deg_pos$pos2)) {
        print('deg2')
        
        aa <- colnames(sub_PWM[i, ])
        aa <- rep(aa, length.out = length(seq) * 20)
        part_score <- unlist(sub_PWM[i, ])
        part_score <- rep(part_score, length.out = length(seq) * 20)
        
        seq <- rep(seq, each = 20)
        score <- rep(score, each = 20)
        
        seq <- str_c(seq, aa)
        score <- score + part_score
        
      }
      
      if (i %in% c(deg_pos$pos)) {
        print('deg2')
        
        aa <- colnames(sub_PWM[i, ])
        aa <- rep(aa, length.out = length(seq) * 20)
        part_score <- unlist(sub_PWM[i, ])
        part_score <- rep(part_score, length.out = length(seq) * 20)
        
        seq <- rep(seq, each = 20)
        score <- rep(score, each = 20)
        
        seq <- str_c(seq, aa)
        score <- score + part_score
        
      }
      
      if (!(i %in% c(deg_pos$pos1, deg_pos$pos2, deg_pos$pos))) {
        aa <- max.col(sub_PWM, ties.method = 'first')[i]
        part_score <- unlist(sub_PWM[i, aa])
        part_seq <- colnames(sub_PWM)[aa]
        seq <- str_c(seq, part_seq)
        score <- score + part_score
      }
      
    }
    
    score_out <-
      tibble(
        family = unique(deg_pos$family),
        aa_seq = seq,
        PWM_score = score
      )
    return(score_out)
  }


