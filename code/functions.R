  merge(df[df$timepoint_end == time, ], 
        ref_df[, c('replicate', 'neg_ref', 'pos_ref', 'condition')], 
        by = c('replicate', 'condition'))


# compute scaling to ref values
df%<>%
  mutate(norm_sel_coef = (sel_coef - neg_ref)/(pos_ref - neg_ref))

return(df)
}


