stat_comp_intra_family <- function(df, vec_family, welch = TRUE, metric = 'norm_sel_coef') {
  signif_all <- tibble()
  for (family in vec_family){
    
    sub_sel_coef <- df[df$family == family, ]
   
    sub_sel_coef %<>%
    group_by(aa_seq) %>%
    drop_na(norm_sel_coef)%>%
    filter(n() >= 2) %>%  # must have 2 groups
    ungroup()

     aa_to_compare <- 
      unique(sub_sel_coef$aa_seq)
    
    aa_ref <- 
    unlist(unique(sub_sel_coef[sub_sel_coef$peptide_max, 'aa_seq' ]))
    
    colnames(sub_sel_coef)[colnames(sub_sel_coef)==metric]<-'metric'
    
    aa_seq_stat <- 
      t_test(sub_sel_coef, metric ~ aa_seq, ref.group = aa_ref, var.equal = !welch, 
      p.adjust.method = 'BH')
    
   
    signif_diff<-  aa_seq_stat[aa_seq_stat$p.adj.signif != 'ns', 'group2']
    
    stronger <- signif_diff$group2 %in% unlist(aa_seq_stat[aa_seq_stat$statistic < 0 & aa_seq_stat$p.adj.signif != 'ns', 'group2'])
    weaker <- signif_diff$group2 %in% unlist(aa_seq_stat[aa_seq_stat$statistic > 0 & aa_seq_stat$p.adj.signif != 'ns', 'group2'])
    
    signif_diff$family <- family
    signif_diff[weaker, 'side'] <- 'weaker'
    signif_diff[stronger, 'side'] <- 'stronger'
    
    signif_all <- bind_rows(signif_all, signif_diff)
  
    
  }
  return(signif_all)
}

