# extract maximal peptide from mutagenesis data
peptide_max <-
  function(df){
    df%>%
      select(family, pool, pos_value, deg_value, signif, side) %>%
      select(family, pool, pos_value, deg_value) %>%
      group_by(family, pool, pos_value) %>%
      pivot_wider(names_from = pos_value, values_from = deg_value) ->inter_pos
    
    # Reorder columns by the numeric value in their name (except for the first columns)
    col_names <- colnames(inter_pos)
    # Assume first columns are 'family' and 'pool', rest are positions
    fixed_cols <- c("family", "pool")
    pos_cols <- setdiff(col_names, fixed_cols)
    # Extract numeric part and order
    pos_cols_ordered <- pos_cols[order(as.numeric(pos_cols))]
    inter_pos <- inter_pos[, c(fixed_cols, pos_cols_ordered)]
    
    inter_pos%>%
      select(family, pool, everything()) %>%
      arrange(family, pool) -> inter_pos
    
    
    return(inter_pos)
  }

get_foldchange <- 
  function(df, repli = c('R1', 'R2', 'R3'), reads = 20){
    for( r in repli){
      z <- df[, c(1, grep(r, colnames(df)))]
      
      tot_reads <- colSums(z[, grep('T', colnames(z))], na.rm = T)
     
      t0<-colnames(z)[grep('T0', colnames(z))]


      z %<>%
      filter(get(t0) >= reads)%>%
        mutate(across(
          all_of(names(tot_reads)),
          ~ . / tot_reads[cur_column()],
          .names = "freq_{.col}"
        ))
      
      name_rep <- colnames(z)[grep('T0_', colnames(z))[1]]
      name_rep <-
        str_c(unlist(strsplit(name_rep, '_'))[2:4], collapse = '_')
      
      col1 <- str_c(c(name_rep, 'foldchange_T1'), collapse = '_')
      col2 <- str_c(c(name_rep, 'foldchange_T2'), collapse = '_')
      
      
      c1 <- tibble(log2(z[, grep('freq_T1.', colnames(z))] / z[, grep('freq_T0.', colnames(z))]))
      colnames(c1) <- col1
      
      c2 <- tibble(log2(z[, grep('freq_T2.', colnames(z))] / z[, grep('freq_T0.', colnames(z))]))
      colnames(c2) <- col2
   
      assign(r, bind_cols('sequence' = z$sequence, c1, c2))
    }
    
    foldchange <- 
      left_join(df, R1)
    
    foldchange <- 
      left_join(foldchange, R2)  
    
    foldchange <- 
      left_join(foldchange, R3)  

    return(foldchange)
  }

get_foldchange_per_condition <- 
  function(df, reads = 20){
    condition2 <-  colnames(df)[grep('T', colnames(df))]
    
    n_con <- 
      unique(unlist(lapply(strsplit(condition2, '_'), `[[`, 5)))
    
    if(length(n_con)==2){
      
      f <- get_foldchange(df)
      return(f)
      }
    
    if(length(n_con)>2){
      
      b <- grep('Both', colnames(df))
      d <- grep('DMSO', colnames(df)) 
      m <- grep('MTX', colnames(df))
      
      d <- df[, c(1:3, b, d)]
      m <- df[, c(1:3, b, m)]
      
      d <- get_foldchange(d, reads = reads)
      m <- get_foldchange(m, reads =reads)
      
      name_d <- grep('fold', colnames(d))
      name_m <- grep('fold', colnames(m))
      
      colnames(d)[name_d] <- 
        paste0(colnames(d)[name_d], '_DMSO')
      
      colnames(m)[name_m] <- 
        paste0(colnames(m)[name_m], '_MTX')
      
      dm <- 
        full_join(d, m[, -c(4:12)])
      
      return(dm)
    }
  }

