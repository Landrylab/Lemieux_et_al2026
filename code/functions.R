get_PWM_from_seq<-
  function(sequence, sub_PWM) {
    score <- 0
    seq_split <- strsplit(sequence, "")[[1]]
    for (i in seq_along(seq_split)) {
      aa <- seq_split[i]
      if (aa %in% colnames(sub_PWM)) {
        score <- score + sub_PWM[i, aa]
      } else {
        score <- NA
        break
      }
    }
    return(score)
  }